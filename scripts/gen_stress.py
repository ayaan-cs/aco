"""Generate the stress and edge-case fixtures under fixtures/stress/.

Deterministic: running it twice produces identical files. Run from the repo
root: python3 scripts/gen_stress.py
"""
import os
import textwrap

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fixtures", "stress")


def write(rel, text, mode="w", newline="\n"):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if mode == "wb":
        with open(path, "wb") as f:
            f.write(text)
    else:
        with open(path, "w", newline=newline) as f:
            f.write(textwrap.dedent(text).lstrip("\n") if isinstance(text, str) else text)


def d(s):
    return textwrap.dedent(s).lstrip("\n")


# --------------------------------------------------------------- large files

FILLER_KINDS = [
    # Unrelated code in assorted shapes; none matches a rewrite rule.
    lambda k: d(f"""
        def stat_{k}(values):
            total = 0
            peak = None
            for v in values:
                total += v * {k % 7 + 1}
                if peak is None or v > peak:
                    peak = v
            return total, peak

    """),
    lambda k: d(f"""
        class Point{k}:
            __slots__ = ("x", "y")

            def __init__(self, x, y):
                self.x = x
                self.y = y

            def norm1(self):
                return abs(self.x) + abs(self.y) + {k}

    """),
    lambda k: d(f"""
        def table_{k}(n):
            rows = {{}}
            for i in range(n):
                rows[i] = (i * {k + 3}) % 97
            return sum(rows.values())

    """),
    lambda k: d(f"""
        def words_{k}(text):
            counts = {{}}
            for w in text.split():
                counts[w] = counts.get(w, 0) + {k % 3 + 1}
            return sorted(counts.items())[:3]

    """),
]


def large(lines_target):
    head = d('''
        # Generated by scripts/gen_stress.py: a large module with the slow
        # patterns buried among unrelated code.


        def sort_scores(xs):
            n = len(xs)
            for i in range(n):
                for j in range(n - 1 - i):
                    if xs[j] > xs[j + 1]:
                        xs[j], xs[j + 1] = xs[j + 1], xs[j]
            return xs


        def count_known(ids):
            known = [k for k in range(0, 9000, 3)]
            hits = 0
            for x in ids:
                if x in known:
                    hits += 1
            return hits


        def tiny_lookup():
            small = [1, 2, 3]
            found = 0
            for v in range(4):
                if v in small:
                    found += 1
            return found


        def render(rows):
            out = ""
            for r in rows:
                out += str(r) + ";"
            return out


    ''')
    tail_tpl = d('''

        def main():
            seed = 7
            data = []
            for _ in range(900):
                seed = (seed * 1103515245 + 12345) % 2147483648
                data.append(seed % 10000)
            ranked = sort_scores(list(data))
            print(ranked[0], ranked[-1], ranked[450])
            print(count_known([d % 9000 for d in data] * 4))
            print(tiny_lookup())
            print(len(render(range(30000))))
            acc = 0
        {calls}    print(acc)


        main()
    ''')
    body = []
    calls = []
    k = 0
    used = head.count("\n") + tail_tpl.count("\n")
    while used < lines_target:
        kind = k % len(FILLER_KINDS)
        chunk = FILLER_KINDS[kind](k)
        body.append(chunk)
        if kind == 0:
            calls.append(f"    acc += stat_{k}([1, 2, 3, {k}])[0]\n")
        elif kind == 1:
            calls.append(f"    acc += Point{k}({k}, -2).norm1()\n")
        elif kind == 2:
            calls.append(f"    acc += table_{k}(20)\n")
        else:
            calls.append(f"    acc += len(words_{k}('a b a c b a'))\n")
        used += chunk.count("\n") + 1
        k += 1
    return head + "".join(body) + tail_tpl.format(calls="".join(calls))


for n in (300, 1000, 3000):
    write(f"large_{n}.py", large(n))

